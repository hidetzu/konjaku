// 外部から来た文字列を、HTML として実行させない。
//
// なぜ要るか（2026-08-15 に実測。配信物は一切変えず、応答だけ page.route で差し替えた）:
//   ev タイル1枚のラベルを `<img src=x onerror="...">` に置き換えて広島を開くと、
//   一覧で 8 回・寄せた先（#fx）でさらに 2 回、合計 10 回発火した。
//   Wikidata のラベルと説明は誰でも編集できる CC0 の第三者データで、こちらが中身を
//   保証できない。地理院の住所検索の応答も、OSM のタグ（種別・建設年）も同じ。
//
// ⚠ 取り込み側では落とさない。取り込み済みの土地と、実行時に問い合わせる土地で
//   答えが変わる（掟: 同じ問いに答える実装を2つ持たない）。**描くときにここを通す**。
//
// ⚠ 表示される文字は変えない。実体参照はブラウザが元の文字に戻して描くので、
//   「＆」や「<」を含む正しい地名がそのまま出る（実描画で textContent を突き合わせている）。
//
// ⚠ 読み上げ（SpeechSynthesis）には通さない。あちらは HTML ではないので、
//   通すと「あんぱさんど えーえむぴー」と読み上げることになる。
//   通す先は「タグを含む文字列を組み立てているところ」だけ。
//
// ⚠ これは1か所にしか置かない（掟: 同じ問いに答える実装を2つ持たない）。
//   scripts/check.mjs が、両ページがこれを読み込んでいることと、
//   外部由来の受け皿が esc() を通っていることを見ている。
window.KonjakuEsc = (function () {
  "use strict";

  // ' も落とす。属性を '…' で囲む書き方が1つでも混ざると、" だけでは破れる
  const MAP = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" };

  // null / undefined は空文字。"null" と描かない
  const esc = (v) => v == null ? "" : String(v).replace(/[&<>"']/g, (c) => MAP[c]);

  // href に入れてよい URL か。
  // ⚠ esc() だけでは `href="javascript:..."` は塞げない。属性は壊れていないので、
  //   引用符を実体参照にしても、押した瞬間に実行される。
  // ⚠ 判定は字面の先頭一致ではなく、URL として解いた結果の scheme で見る。
  //   「 javascript:」（前置の空白）・「JavaScript:」・「java\tscript:」は、
  //   startsWith("http") の裏返しをすり抜ける。
  // ⚠ http/https 以外は空文字を返す。呼ぶ側は、空ならリンクそのものを出さない
  //   （掟: 押しても何も起きない導線を置かない）。
  const escUrl = (v) => {
    const s = String(v ?? "").trim();
    let u;
    try { u = new URL(s, document.baseURI); } catch { return ""; }
    return (u.protocol === "http:" || u.protocol === "https:") ? esc(u.href) : "";
  };

  return { esc, escUrl };
})();
