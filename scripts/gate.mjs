// ⚠ **成長の判定にも、⚠ 最小の分子を置く**（2026-10-10 に足した）。
//
// ⚠ **足す前はこうなっていた**: ⚠ **直近 14 日の外からの訪問が 1 件のとき、
//   ⚠ 1 ÷ 14 = 0.07 を線（0.5）と比べて「⚠ 止まっている」と断じ、
//   ⚠ そこから「⚠ 流入を増やす手だけを採る」という唯一の行動指示を出していた。**
//
// ⚠ **これは、⚠ このファイルの冒頭が自分で禁じていることと同じ形**（⚠ 小さい分母で次を決める）。
//   ⚠ **健康側には最小の分母があるのに、⚠ 成長側には無かった。**
//   ⚠ **`docs/adr/0010` が「小さい分母で次の判断を決めない」と書いている。**
//   ⚠ **検査を足すときは、⚠ その主張が本当に正しいかを疑う**（`CLAUDE.md` §9）。
//
// ⚠ **直し方は「線に照らせる件数が在るか」を先に見る。**
//   ⚠ **線（1 日 0.5 件）を 14 日に当てると 7 件。**⚠ **これが最小の分子。**
//   ⚠ **0 件は観測なので言える**（⚠ 「1 件も無い」）。
//   ⚠ **1〜6 件のときは、⚠ 件数は言えるが「⚠ 止まった」とは言えない**
//     （⚠ 「止まった」と「⚠ たまたま 0 に寄った」を、⚠ この分子では分けられない）。
//   ⚠ **確率は出さない**（`CLAUDE.md` §6）。⚠ **出すのは、⚠ 数えた件数と割り算だけ。**
const 成長を判定する = ({ 外からの訪問, 経過日数, 直近の件数, 直近の日数 = 14 }) => {
  const 線の件数 = Math.ceil(止まっている線 * 直近の日数);
  const 判定 = 直近の件数 >= 線の件数 ? "動いている"
    : 直近の件数 === 0 ? "⚠ 1 件も無い"
    : "⚠ 線に届いていない（⚠ 向きは、この分子では読めない）";
  return {
    一日あたり: 経過日数 ? 外からの訪問 / 経過日数 : null,
    直近の一日あたり: 直近の日数 ? 直近の件数 / 直近の日数 : null,
    線の件数, 判定,
    // ⚠ **流入策を打ったとき、⚠ 効いたかどうかを読めるか。**
    //   ⚠ **読めるのは、⚠ 分子が線の件数に届いてから。**⚠ **足りない分を言う。**
    読むのに足りない: Math.max(0, 線の件数 - 直近の件数),
  };
};

