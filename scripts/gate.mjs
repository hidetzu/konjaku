// ⚠ **窓**（⚠ 成長を、⚠ どの範囲で見るか）。
//
// ⚠ **既定は直近 14 日。**⚠ **`--since=YYYY-MM-DD` を渡すと、⚠ その日から今日まで。**
//   ⚠ **要るのは「手を打った日から」を数えたいとき**（⚠ 掲載を更新した日・記事を出した日）。
//   ⚠ **既定の 14 日だと、⚠ 打つ前と打った後が同じ窓に混ざる**（⚠ 何が効いたか読めない）。
// ⚠ **線は窓の長さに合わせて伸ばす**（⚠ 1 日 0.5 件 × 窓の日数）。⚠ **線そのものは変えない。**
const 窓を読む = (argv, 今日 = new Date()) => {
  const a = argv.find((x) => x.startsWith("--since="))?.slice(8);
  if (!a) return { 種類: "直近", 日数: 14, 名: "直近 14 日", SQL: "date('now','-14 days')" };
  if (!/^\d{4}-\d{2}-\d{2}$/.test(a)) return { 誤り: `--since は YYYY-MM-DD（来たのは ${a}）` };
  const 始め = new Date(`${a}T00:00:00Z`);
  if (Number.isNaN(始め.getTime())) return { 誤り: `--since がその日を指していない（${a}）` };
  // ⚠ **日数は、⚠ 始めの日も入れて数える**（⚠ 当日に打ったなら 1 日）。
  const 日数 = Math.floor((Date.UTC(今日.getUTCFullYear(), 今日.getUTCMonth(), 今日.getUTCDate())
    - 始め.getTime()) / 86400000) + 1;
  // ⚠ **今日が何日かを添える**（2026-10-10 に足した。⚠ **自分で躓いた**）。
  //   ⚠ **記録の日付は UTC**（`public/measure.js` の `訪問`。⚠ `toISOString().slice(0, 10)`）。
  //   ⚠ **日本時間の朝 9 時より前は、⚠ UTC はまだ前の日。**
  //   ⚠ **出した日を `--since` に渡したら「先の日」と言われて、⚠ 理由が分からなかった。**
  if (日数 < 1)
    return { 誤り: `--since が先の日（${a}）。⚠ 記録は UTC の日付で、⚠ 今日は ${今日.toISOString().slice(0, 10)}` };
  return { 種類: "から", 日数, 名: `${a} から ${日数} 日`, SQL: `'${a}'` };
};
