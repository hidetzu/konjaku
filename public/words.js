// 「取得の結末」と「一覧行のタグ」を、画面に出す言葉にする、ただ1か所。
//
// ⚠ **ここに DOM も地図も無い。** 状態を渡すと字が返るだけ。
//   だから Node からそのまま呼べて、検査がブラウザを立てずに全組み合わせを回せる
//   （prov.js / swale.js / ground.js / verify.js と同じ作り）。
//
// なぜ切り出したか（2026-08-20 に実測）:
//   ⚠ **同じ字が 4 ファイルに散っていた。**
//     「記録なし」      index.html / verify.js / share.js   … 3 か所
//     「判定できません」 index.html / verify.js / peel3d.js  … 5 か所
//   ⚠ 片方だけ直すと、**同じ状態に 2 通りの言い方**ができる。
//   ⚠ 実際に踏んでいる: 「まだ提供していない」に 2 通りあり、20 秒のあいだに
//     入れ替わっていた（prov.js の冒頭に記録がある）。
//
// ⚠ **持ち主の分担**（docs/DOMAIN.md §5）
//     ここ            取得の結末の語と、一覧行のタグ。⚠ **2 画面で共有する**
//     prov.js         /peel の台帳の語（実測／未取得／欠落／未対応／推定）
//     peel3d.js WORD  /peel の答えの文
//     index.html TOPWORD  トップの根拠カードと導線の文
//     swale.js        明治期の 14 区分
//     verify.js       年代の定義
//
// ⚠ **字面ではなく、状態の名前で呼ぶこと。**
//   `words.meiji(v, none)` のように**状態を渡す**。呼ぶ側で字を書かない。
((g) => {
  // ⚠ **取得の結末は 5 つ**（docs/DOMAIN.md §3）。⚠ **混ぜない。**
  //
  //   ok          読めた                    … その値
  //   ok かつ 0 件 読めて、該当が無い          … 「記録なし」
  //   absent      その資料がこの土地を対象にしていない … 「整備対象外」
  //   unreachable こちらが読めなかった        … 「読み込めませんでした」
  //   notyet      こちらがまだ用意していない  … 「まだ提供していません」
  //
  // ⚠ **`ok かつ 0 件` に「判定できません」を使わない。**読めているのだから、
  //   「答えを出せなかった」ではない（掟: 取れなかった ≠ 無い の裏返し）。
  const S = {
    // 読めたうえで 0 件。⚠ **「無い」ではなく「記録が無い」。**資料の話に留める
    noRecord: "記録なし",
    // 答えを出せない。⚠ **0 件とは別。**混ぜると 0.0% を実測値として出す事故に戻る
    cantTell: "判定できません",
  };

  // 明治期の区分。value があればそれ、無ければ「読めて 0 件」か「答えを出せない」か。
  // ⚠ **この 2 つを 1 つの語に潰さない。**
  const meiji = (value, none) => value ?? (none ? S.noRecord : S.cantTell);

  // 根拠カードの明治期の行。⚠ **index.html・verify.js・share.js が同じ字を書いていた**
  const meijiBadge = (none) => `明治期: ${none ? S.noRecord : S.cantTell}`;

  // 一覧行のタグ。⚠ **押すと「どこへ行くか」で分ける**（2026-08-20 決定）。
  //   own … 今昔の中で開く（深掘り・年代比較）
  //   why … この土地の判定から出てきた調べもの
  //   ext … 外部のサイトへ出る
  //
  // ⚠ **以前は `根拠あり` だった。**⚠ これは作り手側の分類で、⚠ **利用者が
  //   知りたいのは「押したら何が起きるか」**（ADR 0029「画面の言葉は利用者の問いから決める」）。
  //   ⚠ しかも実態と合っていない: `own` は「根拠がある行」ではなく
  //   ⚠ **「今昔の中で開くレンズ」**（深掘り・年代比較）。`why` の側にも根拠はある。
  //
  // ⚠ **`priv`（自分）は 2026-08-20 に消した。**付ける場所がどこにも無く、
  //   ⚠ **画面に出ようがない語**だった（掟: 押しても何も起きない導線を置かない の同類）。
  const TAG = { own: "今昔で見る", why: "この土地から", ext: "別のサイト↗" };
  // ⚠ **知らない tag は ext 扱い**。⚠ ここが唯一の既定値（呼ぶ側に写さない）
  const tag = (t) => TAG[t] ?? TAG.ext;

  // ============================================================
  // 根拠カードの、取得方法のバッジ
  //
  // ⚠ **利用者の問いは「これはどれくらい確かか」。**
  //   ⚠ `直読み` `ベクトル直読み` は**取り方**の話で、⚠ **確かさを語っていない**
  //     （2026-08-20 に言い直した。ADR 0029「画面の言葉は利用者の問いから決める」）。
  //
  // ⚠ **verify.js が渡すのは、字ではなく鍵。**⚠ **字はここだけが持つ。**
  //   ⚠ 以前は verify.js が `method: "直読み"` と**画面に出る字を直接**持っていた。
  const METHOD = {
    read:       "読んだ値",        // タイルの画素・図式コードを、そのまま読んだ
    readVector: "読んだ値",        // ⚠ ベクトルでも、利用者から見た確かさは同じ
    calc:       "読んで計算した",  // 読んだ値から出した
    est:        "こちらで立てた値", // ⚠ **実測ではない**
  };
  // 近傍で区分が割れている。⚠ **言い切らない**ことを、バッジの側でも言う
  const EDGE = "近くで分かれている";
  // ⚠ **読めていないものを「読んだ値」と言わない**（掟の一行目）
  const UNREAD = "読み込めませんでした";

  // ⚠ **状態を渡す。呼ぶ側で字を組み立てない。**
  //   ⚠ 知らない鍵のときは**何も出さない**。⚠ **内部の鍵を画面に漏らさない**し、
  //     ⚠ **読んだとも推定したとも言わない**（どちらも嘘になりうる）。
  //     ⚠ 鍵の取りこぼしは check.mjs が静的に捕まえる。
  const method = (state, mixed, key) =>
    state === "unreachable" ? UNREAD : mixed ? EDGE : (METHOD[key] ?? "");

  // ============================================================
  // プライバシーの 3 段（載る → 届く → 残らない）
  //
  // ⚠ **1 段でも落とすと、いちばん強い約束だけが残って「通信していない」と読める**
  //   （2026-08-15 に実際そうなっていた）。⚠ **3 段そろえて 1 つの文。**
  //
  // ⚠ **順番を変えない。**「計測には送らない」だけを先に書くと、また言い切りすぎになる。
  //
  // ⚠ **2 画面が同じ文を出す**（トップの検索欄の下と、/peel の情報パネル）。
  //   ⚠ **だから 1 か所で持つ。**⚠ 以前は /peel だけが持っていて、
  //     トップは畳んだフッターの中にしか無かった（⚠ **送る前に読めなかった**）。
  //
  // ⚠ **詳しい説明は消さない。**これは要約で、全文はトップのフッターにある。
  const PRIVACY_SHORT =
    "調べた場所は<b>URL に入り</b>、開くと<b>配信元（Cloudflare）に届きます</b>。"
    + "<b>こちらの記録には残りません</b>（計測に地名も座標も送らず、Cookie も使いません）。";

  // ============================================================
  // 写真が届いていないときに、何と言うか
  //
  // ⚠ **状態を決めるのは photos.js。**⚠ **字を決めるのはここ。**⚠ **置き方は画面。**
  //   ⚠ この 3 つを分ける（2026-08-20 のオーナー指示）。
  //   ⚠ **相手先の振る舞いが変わっても、直すのは photos.js の 1 か所。**
  //   ⚠ **言い方を変えるなら、直すのはここの 1 か所。**⚠ **画面は触らない。**
  //
  // ⚠ **画面から「何の写真か」を渡させない。**⚠ 渡させると、⚠ **その判断が画面ごとに増える**
  //   （2026-08-20 の途中まで、トップと /peel が別々に組み立てていた）。
  //   ⚠ **photos.js が状態と一緒に era の素性を返すので、それを見る。**
  //
  // ⚠ **知っていることだけ言う。**
  //   fail    … ⚠ **落ちたのを実際に観測した。**理由まで言える
  //   late    … ⚠ **理由を知らない。**⚠ **「読み込めませんでした」と言わない**
  //   pending … 猶予の中。⚠ **何も言わない**（言うと読み込みのたびに光る）
  //   ok      … 何も言わない
  //
  // ⚠ **返すのは「画面が判断できる情報」。**⚠ **どう置くかは決めない。**
  //   lead … 頭に出す短い名乗り（無いこともある）
  //   body … 本文
  //   hint … 接続の話（⚠ **知っているときだけ**。無いこともある）
  const photoSay = (state) => {
    if (!state || state.kind === "ok" || state.kind === "pending") return null;
    const e = state.era ?? {};
    // ⚠ 「何の写真か」は、状態が持っている素性から決める。⚠ **画面に組み立てさせない**
    const what = e.isMeiji ? "明治期の地面" : e.isLatest ? "いまの街の写真" : "この年代の写真";
    if (state.kind === "late")
      // ⚠ **理由を断定しない。**404 は「遅い」と区別できない
      return { lead: "選択中", body: `${what}は、まだ出ていません`, hint: "" };
    // fail
    return {
      lead: "出せません",
      body: `${what}を読み込めませんでした（${state.why}）`,
      // ⚠ **onLine が false のときだけ言い切る。**⚠ **こちらが知っている範囲でしか言わない**
      hint: state.online === false ? "インターネットに接続していません" : "接続を確認してください",
    };
  };

  // ---- 土地の答えの、問いと文 ----
  //
  // ⚠ **層の名前は、その層が答えている「問い」で呼ぶ**（docs/DOMAIN.md §1、ADR 0029）。
  //   ⚠ 「第1層」「第2層」は内部の呼び名。**画面に出さない**。
  // ⚠ **2026-08-20 に peel3d.js の WORD から移した。**⚠ トップにも同じ見出しを出すので、
  //   ⚠ **持ち主が 2 か所になる**のを避けた（掟: 同じ問いに答える実装を2つ持たない）。
  const LAYER_TITLE = {
    1: "ここは、どういう土地？",
    2: "昔は、何があった？",
    3: "いま建っている建物は、何の上？",
  };
  const layerTitle = (n) => LAYER_TITLE[n] ?? "";

  // ⚠ 第1層の文。⚠ **ADR 0030 §4 が決めたとおりに組む。**
  //   1 主語は「この土地は」に統一（実測 9:1。利用者役 2/4 が「この場所」と別物と読んだ）
  //   3 「もとは」を使わない（3/4 が明治期＝第2層と取り違えた）
  //   4 成因と人工改変は行を分ける（1 行に混ぜると「もとから埋立地だった」に読める）
  //   5 原典の語をそのまま出す（平易な言い換えを足さない。時間の語を使わずに済む）
  //
  // ⚠ **行で返す。**⚠ 1 本の文字列にして返すと、⚠ **受け取る側が割り方を決めることになり、
  //   画面ごとに割れ方が変わる**（4 が守れない）。
  // ⚠ **em は区分名の強め方。**画面は太字、共有カードの文は素のまま。
  //   ⚠ **強めるかどうかは見た目の話なので、呼ぶ側が決める。**⚠ 語はここが決める。
  const ground1Lines = (name, artificial, em) => {
    const b = em ?? ((s) => s);
    const out = [`この土地は ${b(name)}`];
    if (artificial) out.push(`人の手で ${b(artificial)} になっています`);
    return out;
  };

  // ⚠ 1 本にまとめて読む相手（共有カードの文・読み上げ）のための形。
  //   ⚠ **行の作り方は上の 1 か所。**ここは繋ぎ方だけを決める。
  const ground1Text = (name, artificial) =>
    ground1Lines(name, artificial).join("。") + "。";

  g.KonjakuWords = { S, meiji, meijiBadge, TAG, tag, METHOD, EDGE, UNREAD, method,
                     PRIVACY_SHORT, photoSay,
                     LAYER_TITLE, layerTitle, ground1Lines, ground1Text };
})(typeof window === "undefined" ? globalThis : window);
