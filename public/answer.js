// 見出しと 2 行目の字を決める。v0.1.0 だけのもの。
//
// なぜ words.js に置かないか:
//   words.js は β 版から 1 バイトも違わない形で運んでいる（test/check/next.mjs ⑤）。
//   そこへ v0.1.0 だけの都合を書くと、突き合わせが成り立たなくなり、
//   36 区分の言い換え（GROUND_GLOSS）が β 版と静かにずれる道ができる。
//   区分の言い換えは words.js から借りる。ここでは作らない。
//
// 何を決めるか:
//   名乗り「この土地は、昔なんだったのか？」に、いちばん大きい字で答える。
//   前は「確実性の高い順」だった（docs/adr/0030）。常に取れる地形分類が見出しで、
//   明治期はその下の小さい行だった。
//   実測（2026-08-30・利用者役 5 名中 3 名。実在の利用者ではない）:
//     春日部と軽井沢で「これは昔の答えではない」と読まれた。
//     春日部は「明治期は 田」を既に出していた。見出しでなかっただけ。
//   順を変えても、出典と確かさの扱いは弱めない。名乗りも変えない。
//
// DOM も地図も持たない。Node から呼べるので、検査がブラウザ抜きで回せる。
(function (g) {
  "use strict";

  // 出典の名前。見出しの上に小さく置き、「なぜそう言える？」の行の見出しと同じ語を使う。
  //   2 つの資料が独立に同じことを言っているのが価値なのに、
  //   出典を名乗らないと、見出しと 2 行目が「同じことの繰り返し」に読まれた
  //   （利用者役 5 名中 3 名。2026-08-31。実在の利用者ではない）。
  //   ラベルに出すと、見出しから出典名が抜けて短くなる。
  //   実測（375×667）: 豊洲の見出しが 2 行 → 1 行、カード 315 → 303px。
  const SOURCE = { meiji: "明治期の地図", terrain: "いまの地形" };

  // 明治期が答えを出せない 3 つの状態。混ぜない（docs/adr/0056）。
  //   1 文にまとめない。「取れなかった」と「無い」は別のこと。
  //   主語は上のラベル（明治期の地図）が補う。だから字の中で繰り返さない。
  //   同じ字を、見出しと「なぜそう言える？」の両方で使う。
  //   2 か所に別の字を持つと、片方だけ古くなる。
  //
  //   「作られていません」をやめた（2026-08-31。Owner 指示）。
  //   否定された動作は「まだ作っていない」「壊れている」に読まれる
  //   （利用者役 5 名中 2 名が「アプリが壊れているか、自分の通信のせいかと思った」）。
  //   資料が どこを対象にしているか の事実として言う。CLAUDE.md §4 が例に挙げている形。
  //   限界は消していない。順番と主語と時制だけを変えた（§4-1）。
  //
  //   さらに「対象の範囲の外です」もやめた（2026-09-01。Owner 指示）。
  //   仮想利用者 6 名中 3 名が、資料ではなくアプリ全体の話に読んだ
  //   （「ここでは使えません」「エラーっぽい」「このアプリで軽井沢を調べられない」）。
  //   「対象」の持ち主が、字の中に無かった。
  //
  //   3 つとも主語を「この地図」にした。上のラベル（明治期の地図）を受ける形。
  //   ラベルと字が親子になり、何の話かが字の中で閉じる。
  //   ラベルの語をそのまま繰り返さない（画面で同じ字が 2 回並ぶ）。
  //   3 つは別の字のまま（ADR 0056。無い・区分が無い・読めなかったは別）。
  const MEIJI_NONE = {
    absent:      "この地図は、この地域を含んでいません",
    noClass:     "この地図に、この場所の区分はありません",
    unreachable: "この地図を、いま読み取れませんでした",
  };

  // 地形分類そのものが「昔の姿」を名指す区分。
  //   明治期が無くても、ここに在る区分なら見出しに使える。
  //   3 つだけ（2026-08-31 に 36 区分を読んで数えた）。
  //   「切土地（前は斜面）」「農耕平坦化地（前は山）」は入れない。
  //   前の姿を名詞で名指しておらず、何になったかしか言っていない。
  //   綴りは landform.json が正本。ずれたら検査が落とす。
  const PAST_IN_TERRAIN = ["旧水部", "旧河道", "干拓地"];

  // 順番は「問いへの近さ」。
  //   1 明治期に区分がある      「明治期、ここは 田 でした」
  //   2 地形分類が昔を名指す    その字をそのまま（新しく書かない）
  //   3 どちらも無い            なぜ無いかを、状態ごとに言い分ける
  //
  // meiji は { value } か { none }。null / undefined は「まだ来ていない」。
  //   来ていないうちは呼ばない（呼ぶ側が待つ）。ここで「取れなかった」に倒さない。
  // 2 行目は地形分類の成り立ち。見出しが地形分類そのもののときは重ねない。
  // 返すのは label / head / sub の 3 つ。label は出典の名前で、見出しの上に置く。
  //   2 行目は自分の出典を字の中に持つ（いまの地形は、…）ので、ラベルは付けない。
  //   両方にラベルを付ける版も測ったが、カードが 春日部で 337 → 372px になった。
  //   ラベル 1 つなら 豊洲 315 → 303px・軽井沢 280 → 268px で、むしろ縮む。
  const lines = ({ terrain, meiji }) => {
    const gloss = g.KonjakuWords.groundGloss(terrain);
    const 成り立ち = gloss ? `${SOURCE.terrain}は、${gloss}` : "";
    if (meiji && meiji.value)
      return { label: SOURCE.meiji, head: `ここは ${meiji.value} でした`, sub: 成り立ち };
    // 地形分類そのものが昔を名指す。出典は 2 行目と同じなので、ラベルはそちらに任せない。
    //   見出しが地形分類の字そのものなので、ラベルもそう名乗る。
    if (PAST_IN_TERRAIN.includes(terrain))
      return { label: SOURCE.terrain, head: `ここは、${gloss}`, sub: "" };
    return { label: SOURCE.meiji, head: MEIJI_NONE[meiji && meiji.none] ?? "", sub: 成り立ち };
  };

  g.KonjakuAnswer = { SOURCE, MEIJI_NONE, PAST_IN_TERRAIN, lines };
})(typeof window === "undefined" ? globalThis : window);
