// ⚠ **これは「働かない Service Worker」。**⚠ **自分を消すためだけに在る。**
//
// ⚠ **なぜ要るか**（2026-09-01。`docs/adr/0080`）。
//   ⚠ **β 版は `/sw.js` を root scope で登録していた**（⚠ `index.html` と `peel.html` の両方）。
//   ⚠ **一度でも β 版を開いた端末には、⚠ その SW が入ったまま残っている。**
//   ⚠ **SW は配信より先に応答するので、⚠ 消さないと、⚠ v0.1.0 を出しても
//     ⚠ その端末には β 版の `/` が出続ける。**
//
// ⚠ **ファイルを消すだけでは足りない、と考えて残す。**
//   ⚠ **「404 になれば登録も消える」という挙動はあるが、⚠ こちらでは確かめていない。**
//   ⚠ **確かめていないことに頼らない**（`CLAUDE.md` §1）。⚠ **自分で消す。**
//
// ⚠ **v0.1.0 はオフラインを持たない**（2026-09-01。Owner 判断）。
//   ⚠ **ここに機能を足さない。**⚠ **足すなら、⚠ そのとき改めて決める。**
//
// ⚠ **このファイルは持たせない**（`public/_headers` の `/sw.js` は `no-store`）。
//   ⚠ **持たれると、⚠ 消しに来た本人が古いまま残る。**

// ⚠ **待たずに引き継ぐ。**⚠ **古い SW を、⚠ すぐ置き換える。**
self.addEventListener("install", () => self.skipWaiting());

self.addEventListener("activate", (e) => {
  e.waitUntil((async () => {
    // ⚠ **β 版が作った控えを、⚠ 名前で選ばずに全部消す。**
    //   ⚠ **名前で選ぶと、⚠ 版が変わっていたときに取り残す。**
    //   ⚠ **この origin の控えは、⚠ もう誰も使わない。**
    for (const k of await caches.keys()) await caches.delete(k);

    // ⚠ **自分を消す。**⚠ **これ以降、⚠ この origin に SW は居ない。**
    await self.registration.unregister();

    // ⚠ **開いている頁を読み直させる。**⚠ **`unregister()` は、⚠ いま制御している頁を手放さない。**
    //   ⚠ **読み直さないと、⚠ その頁は閉じるまで β 版のまま。**
    for (const c of await self.clients.matchAll({ type: "window" })) c.navigate(c.url);
  })());
});

// ⚠ **何も横取りしない。**⚠ **`fetch` を持たない SW は、⚠ 配信をそのまま通す。**
