// 「いま画面に出ているもの」＝台帳を組み立てる、ただ1か所。
//
// ⚠ **ここに DOM も地図も無い。** 状態を渡すと行が返るだけ。
//   だから Node からそのまま呼べて、検査がブラウザを立てずに全組み合わせを回せる
//   （verify.js / swale.js / ground.js と同じ作り）。
//
// なぜ切り出したか（2026-08-18 に実測）:
//   台帳は render() の中で組まれていた。render() は再生中**毎フレーム**走るので、
//   実測で **1 回の再生（11.1 秒）に 299 回**、17 要素を作り直していた。
//   台帳が変わるのは「段が変わったとき」と「データが届いたとき」だけなので、
//   組み立てと書き込みを分けないと、周期の違う 3 つが同じ速さで動く。
//
// ⚠ **語彙は 5 つだけ。増やすときはここに書いて、意味を決めてから使う。**
//   この 5 つの区別が掟そのものなので、字面ではなく **tag** で検査する。
//
//     実測  読んだ。その結果をそのまま出している
//     未取得 読めなかった。⚠ **無いとは言っていない**
//     欠落  読んだうえで、本当に無い
//     未対応 こちらがまだ用意していない。⚠ **通信の話ではない**
//     推定  こちらが立てた値。実測ではない
//
// ⚠ 「未取得」の行には、**必ず**「無いとは限らない」側の但し書きを付ける。
//   付け忘れると、読めなかったことが「無かった」に読める（掟の一行目）。
((g) => {
  const OK = "ok", NO = "no", EST = "est";

  // ⚠ **「まだ提供していない」の言い方は、ここ 1 つ。**
  //   実測（2026-08-18）: 同じ事実に 2 通りの言い方があった。
  //     待っているあいだ … 「この場所の建物データは、まだ用意できていません」
  //     終わったあと     … 「建物ごとの判定は、この場所ではまだ提供していません」
  //   ⚠ 20 秒のあいだに**言い方が入れ替わる**ので、同じことだと分からない。
  // ⚠ 主語は「建物データ」ではなく **「建物ごとの判定」**。
  //   建物そのものは（Overpass から取れれば）出る。出せないのは**足元の判定**のほう。
  const NOTYET = "建物ごとの判定は、この場所ではまだ提供していません";
  // ⚠ 3 つセットで使う。⚠ 1 つ目を落とすと、利用者は自分の通信を疑う（利用者役 3/3）。
  const NOTYET_WHY = "通信の問題ではありません。対応した場所から順に増やしています。\n"
                   + "現地に建物が無いという意味でもありません";

  // 地表。いま地面として出している 1 枚が、本当に届いたか。
  // ⚠ 届いていないときに「実測」と書かない。ここは画面でいちばん広い面なので、
  //   水面・建物に入れたガードを、いちばん大きく破れる場所でもある。
  const groundRow = (arrived, era) => arrived
    ? { q: 2, level: OK, tag: "実測",
        body: `地表は${era ? "<b>その年代の空中写真</b>" : "<b>明治期の低湿地データ</b>"}そのもの。加工なし` }
    : { q: 2, level: NO, tag: "未取得",
        body: `地表の${era ? `<b>${era.label}の空中写真</b>` : "<b>明治期の低湿地データ</b>"}が届いていない`,
        note: "届いていないだけで、この年代の記録の有無は分かっていない" };

  // 水面。読めた／読めなかった／本当に無い、を混ぜない
  const waterRow = (area) => (!area || area.waterRead)
    ? { q: 2, level: OK, tag: "実測", body: "水面の形は低湿地データから起こした<b>実際の水域</b>" }
    : { q: 2, level: NO, tag: area.waterUnread ? "未取得" : "欠落",
        body: area.waterUnread ? "明治期の低湿地データを読み込めていない"
                               : "この範囲に明治期の低湿地データが無い" };

  // 建物。⚠ 0 件は「無い」ではなく**読んだ結果**なので実測の側に置く。
  //   以前は件数の真偽だけで分岐していたので、待っている間も正常な 0 件も
  //   同じ「欠落」と書いていた。
  const buildingRows = (area) => {
    if (!area || area.bldState === "loading")
      return [{ q: 3, level: NO, tag: "未取得", body: "建物データを<b>取得中</b>",
                note: "まだ届いていないだけで、この範囲の建物の有無は分かっていない" }];
    // ⚠ **進行形を使わない。**「取得中」「届いていない」は、利用者役 3/3 が
    //   そろって自分の通信の話として読んだ。今この瞬間に動いている感じが出るため。
    // ⚠ **「通信の問題ではありません」と言い切る。**野暮でも書く。
    if (area.bldState === "notyet")
      return [{ q: 3, level: NO, tag: "未対応",
                body: NOTYET.replace("この場所ではまだ提供していません",
                                     "<b>この場所ではまだ提供していません</b>"),
                // ⚠ **「代わりにできること」を、⚠ 断りに添える**（2026-08-22。Owner 判断。
                //   `CLAUDE.md` §4-1）。⚠ **字は `words.js` の 1 か所から借りる**
                //   （⚠ トップの導線と同じ幹）。⚠ **問いの答えの位置には置かない。**
                note: `${NOTYET_WHY}\n代わりに、${
                  (g.KonjakuWords?.canWithoutBuildings?.("peel") ?? "")
                    .replace(/^空中写真/, "空中写真")}` }];
    if (area.bldState === "fail")
      // ⚠ **取れなかったときは、⚠ 復帰手段を添える**（掟: 取れなかったを「無い」と言わない）。
      //   ⚠ **前は `#status` にしか無かった。**⚠ **断りのすぐ隣へ移した**（2026-08-22。Owner 判断）。
      //   ⚠ **HTML はここで作らない。**⚠ 呼ぶ側が `retry` を見て的を置く（`prov.js` は DOM を知らない）。
      return [{ q: 3, level: NO, tag: "未取得", body: "建物データを<b>取得できていない</b>", retry: true,
                note: "届いていないだけで、この範囲の建物の有無は分かっていない" }];
    // ⚠ どの資料で 0 件だったかまで書く（台帳は出所を書く欄）
    if (!area.total)
      return [{ q: 3, level: OK, tag: "実測",
                body: area.bldSource === "overpass" ? "OSM への問い合わせで<b>建物 0 件</b>"
                                                    : "取り込み済みの建物データで<b>建物 0 件</b>",
                note: "OSM に登録が無いだけで、現地に建物が無いとは限らない" }];

    const out = [];
    // ⚠ 高さは「いま見えている形」そのもの。消える年代の演出より手前の事実なので先に置く。
    if (area.hSrc)
      // ⚠ **高さと建設年の件数は、⚠ 内訳が持つ**（2026-08-22。Owner 判断）。
      //   ⚠ **前はここが「1373 / 5038 件が実測」を言い、⚠ 内訳も同じ数字を言っていた。**
      //   ⚠ **同じ分母・同じ数字を 2 か所で言わない**（掟 §6）。
      //   ⚠ **ここに残すのは「どうやって決めたか」だけ**（⚠ 材料の話）。
      out.push({ q: 3, level: EST, tag: "推定",
        body: "実測でない高さは、<b>種別ごとの既定値</b>で立てています",
        note: "（建物の形は、高さだけこちらが決めた値になります）" });
    // ⚠ **こちらも、⚠ できることから書く**（2026-08-22。Owner 判断。高さと同じ作法）。
    //   ⚠ **前は「建物が消える年代は、⚠ こちらが立てた概算。」から始まっていた。**
    //   ⚠ **1 件も分かっていないときは、⚠ できることが無い。**⚠ そのときだけ、
    //     ⚠ **先に「分かっていない」と言う**（⚠ 無い事実をやわらげない。掟 §1）。
    // ⚠ **件数は内訳が持つ**（2026-08-22）。⚠ **ここは「どうやって決めたか」だけ。**
    // ⚠ **「年が分からない建物が消える年代は」を書き換えた**（2026-08-23。Owner 判断）。
    //   ⚠ **利用者役 2/4 が 1 回で読めず、⚠ 1 名が「建物が消えるとはどういうことか」と聞いた。**
    //   ⚠ **いつの話か（年代を戻したとき）が抜けていた。**⚠ **主語ではなく場面を先に置いた。**
    // ⚠ **画面の `⚠` は災害リスク専用**（`CLAUDE.md` §4-1）。⚠ **2 か所の断りから外した**
    //   （2026-08-23。Owner 判断。⚠ **利用者役 1 名が「この建物は危ないという意味か」と聞いた**）。
    //   ⚠ **消したのは印だけで、⚠ 断りの字はそのまま残っている。**
    out.push({ q: 3, level: EST, tag: "推定",
      body: "年代を戻したとき、年が分からない建物が<b>いつ消えるか</b>は、こちらが決めた見込みです",
      note: "（根拠は「足元が水なら埋立前には無い」だけ）" });
    return out;
  };

  // 足元の判定が届かなかった建物
  const unreadRow = (area) => (area && area.unread)
    ? [{ q: 3, level: NO, tag: "未取得", body: `${area.unread} 件は足元の判定ができていない`,
         note: "読み込めなかっただけで、明治期のデータが無いとは限らない" }]
    : [];

  // ⚠ **由来（いつ取り込んだか・何面を起こしたか）**（2026-08-22。hidetzu/konjaku#153。Owner 判断 3）。
  //   ⚠ **前は判定結果の行（`#status`）に混ざっていた。**
  //     ⚠ あちらは「⚠ **いま判定できたか**」を言う場所で、⚠ **こちらは「その材料がどこから来たか」。**
  //   ⚠ **取り込んだ日は「いつの現実か」ではない。**⚠ **こちらがいつ取り込んだか**でしかないので、
  //     ⚠ **そう読めるようにだけ書く**（掟: 推定を実測のように見せない）。
  //   ⚠ 取り込んだ日が分からないときは、⚠ **行を出さない**（⚠ 「不明」と書かない）。
  const sourceRow = (s) => {
    const out = [];
    if (s.blAt)
      out.push({ q: 3, level: OK, tag: "実測", body: `建物のデータは <b>${s.blAt}</b> に取り込んだもの`,
        note: "そのあとに建った・消えた建物は入っていない" });
    if (s.area && s.area.waterRead && typeof s.waterRects === "number")
      out.push({ q: 2, level: OK, tag: "実測",
        body: `水面は、明治期の低湿地データから <b>${s.waterRects} 面</b>を起こしたもの`,
        note: "面の数は、この範囲で読めた区画の数" });
    return out;
  };

  // ⚠ **第1の問い（ここはどんな土地？）を支える行**（2026-08-22。Owner 判断）。
  //   ⚠ **新しく取りに行かない。**⚠ `public/data/landform.json` に ⚠ **既に配ってある**
  //     区分ごとの原典（`why`）を、⚠ **分類し直して出すだけ**。⚠ 通信は 1 本も増えない。
  //   ⚠ **原典はそのまま。**⚠ こちらで要約しない（ADR 0030 §4-5・ADR 0031）。
  //   ⚠ **区分が読めていないときは、行を出さない**（⚠ 「不明」と書かない）。
  const landRow = (s) => {
    const L = s && s.landClass;
    if (!L || !L.name) return [];
    const out = [{ q: 1, level: OK, tag: "実測",
      body: `この区分は<b>国土地理院の土地条件データ</b>から読んだもの`,
      note: L.why || "" }];
    // ⚠ **人の手が入っているかは、⚠ 別の行**（成因と人工改変を 1 行に混ぜない。ADR 0030 §4-4）
    if (L.artificial)
      out.push({ q: 1, level: OK, tag: "実測",
        body: `人の手が入った区分は<b>${L.artificial}</b>`,
        note: L.artificialWhy || "" });
    return out;
  };

  // 出ているものだけを説明する。出ていないものの出所は書かない
  const rows = (s) => [
    ...landRow(s),
    groundRow(s.groundArrived, s.era),
    waterRow(s.area),
    ...buildingRows(s.area),
    ...unreadRow(s.area),
    ...sourceRow(s),
  ];

  // 行 → HTML。⚠ **HTML を作るのはここだけ。**
  //   行を足すときに `<div class="prov">` を自分で書き始めないこと。
  // ⚠ body と 但し書きのあいだは**改行1つ**。HTML では空白1つに潰れるが、
  //   詰めると innerText が 1 文字変わる（検査が字面で読んでいる）。
  // ⚠ **「実測」のタグは出さない**（2026-08-22。Owner 判断）。
  //   ⚠ 実測（利用者役 4 名に画面だけを見せた。⚠ **実在の利用者ではない**）:
  //     ⚠ **4/4 が読み違えた。**⚠ 2 名が「誰かが現地で測った」、
  //       ⚠ 1 名が「この判定が実測で裏取りされている」と読んだ。
  //     ⚠ **`prov.js` の定義は「読んだ。その結果をそのまま出している」**で、
  //       ⚠ **こちらが読んだ、という意味。**⚠ **より強い主張に読まれた。**
  //   ⚠ **本文が「〜から読んだもの」と既に言っている。**⚠ タグは同じことの繰り返し。
  //   ⚠ **5 つで 1 組の語彙は、⚠ 台帳に並んでいたから意味を持っていた。**
  //     ⚠ 問いの下へ配ったので、⚠ **比べる相手がいなくなった。**
  // ⚠ **残りの 4 つ（推定・未取得・欠落・未対応）は出す。**
  //   ⚠ **あちらは「普通でない」印**で、⚠ **見落とすと掟に反する。**
  // ⚠ **タグは出さない**（2026-08-22。Owner 判断: ⚠ 「未対応」の文字は要らない。⚠ 色で伝わる）。
  //   ⚠ **色だけで区別することにはならない。**⚠ **4 つとも、⚠ 本文が状態を字で言っている**
  //     （実測 2026-08-22）:
  //       未対応 「建物ごとの判定は、この場所ではまだ提供していません」
  //       未取得 「建物データを取得できていない」
  //       欠落   「この範囲に明治期の低湿地データが無い」
  //       推定   「実測でない高さは、種別ごとの既定値で立てています」
  //     ⚠ `ui-ux-review` が禁じるのは ⚠ **色と位置だけで状態を言うこと。**⚠ 字がある。
  //   ⚠ **1 つだけ消すと不揃いになる**ので、⚠ **4 つとも消す**（⚠ 「実測」は先に消してある）。
  //   ⚠ **語彙（tag）は行のデータに残す。**⚠ **検査は字面ではなく tag で見ている**（`prov.js` 冒頭）。
  const html = (list) => list.map((r) =>
    `<div class="prov ${r.level}">${r.body}`
    + (r.note || r.peek || r.retry
        ? `\n<span class="d">${r.note || ""}`
          + (r.peek ? `<button class="peek" id="${r.peek.id}">${r.peek.label}</button>` : "")
          // ⚠ **再試行の的。**⚠ 押したときに何をするかは、⚠ 呼ぶ側が繋ぐ（`wireRetry`）
          + (r.retry ? `<button class="retry-btn">再試行</button>` : "")
          + "</span>"
        : "")
    + "</div>").join("");

  // ⚠ **問いごとに配る**（2026-08-22。Owner 判断: ⚠ **「使用しているデータ・状態」をやめる**）。
  //   ⚠ **利用者は「使用しているデータ・状態」が何の話か分からなかった**（Owner 実測）。
  //   ⚠ **材料の話は、⚠ その材料が支えている問いの下に置く。**
  const byQuestion = (s) => {
    const out = { 1: [], 2: [], 3: [] };
    for (const r of rows(s)) (out[r.q] ?? out[3]).push(r);
    return out;
  };

  // ⚠ **畳んでよいのは「実測」だけ**（2026-08-22）。
  //   ⚠ **畳んだ `<details>` の中身は、⚠ 画面にも innerText にも出ない**（`peel.html` に実測）。
  //   ⚠ だから ⚠ **「未取得」「欠落」「未対応」「推定」は畳まない。**
  //     ⚠ 畳むと、⚠ **推定の高さで建物が立った絵を、断りなしに見せる**（掟 §1）。
  //   ⚠ **消すのではない。**⚠ **読む手間の差だけを付ける。**
  // ⚠ **答えが出せない問いには、⚠ 「詳しく見る」を出さない**（2026-08-23。Owner 判断）。
  //   ⚠ **実測（網走市・1280×950）**: 「昔はどんな土地？」は
  //     ⚠ 「この範囲に明治期の低湿地データが無い」と言ったすぐ下に ⚠ **「詳しく見る」があった。**
  //     ⚠ **答えが無いのに、⚠ 何を詳しく見るのか分からない。**
  //   ⚠ **「今建っている建物は？」に合わせる**（⚠ あちらは取れないとき出ていない）。
  //   ⚠ **断り（`level !== OK`）は消さない。**⚠ **畳んでいた実測の行だけ出さない**（掟 §1）。
  const section = (list, whyLabel, hasAnswer = true) => {
    const always = list.filter((r) => r.level !== OK);
    const folded = hasAnswer ? list.filter((r) => r.level === OK) : [];
    return html(always)
      + (folded.length
          ? `<details class="drill"><summary>${whyLabel}</summary>${html(folded)}</details>`
          : "");
  };

  // ⚠ 「読めなかった」と言う行。ここに挙がっている tag は、
  //   **無いと断定する文を持ってはいけない**（検査がこの表を使う）
  const TAGS = { OK: "実測", ABSENT: "欠落", UNREAD: "未取得", NOTYET: "未対応", EST: "推定" };

  g.KonjakuProv = { rows, html, byQuestion, section, landRow,
    groundRow, waterRow, buildingRows, unreadRow, sourceRow, TAGS,
    // ⚠ 画面のほかの場所も、この文を借りる（書き写さない）
    NOTYET, NOTYET_WHY };
})(typeof globalThis !== "undefined" ? globalThis : this);
